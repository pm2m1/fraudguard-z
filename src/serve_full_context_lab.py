"""Explicitly opted-in, localhost-only full-context simulator launcher.

Do not use for real payment routing or represent as validated fraud detection.
No Model B files, prior holdout data or training scripts are accessed.
"""
import json
import os
from pathlib import Path

import joblib
import numpy as np

from .full_context_api import create_full_context_app
from .full_context_calibration import INDICES, MODEL_NAME, verify_model
from .full_context_journal import FullContextJournal
from .full_context_materialize import file_sha256
from .full_context_policy_v2 import OUTPUT as POLICY_OUTPUT
from .full_context_policy import CANDIDATES, CALIBRATION

ROOT = Path(__file__).resolve().parents[1]
DB_DEFAULT = ROOT / "data/runtime/full_context_lab_v2.sqlite3"


def load_frozen_lab_artifacts(candidates=CANDIDATES, calibration=CALIBRATION,
                              policy=POLICY_OUTPUT / "policy.json"):
    model_path, digest = verify_model(candidates)
    calibration = Path(calibration)
    cal = json.loads((calibration / "calibration.json").read_text())
    cp = calibration / "calibrator.joblib"
    if (cal.get("status") != "PROVISIONAL_CALIBRATION_FIT_ONLY"
            or cal.get("model_name") != MODEL_NAME
            or cal.get("model_sha256") != digest
            or cal.get("feature_indices") != list(INDICES)
            or cal.get("block_enabled") is not False
            or cp.is_symlink() or not cp.is_file()
            or file_sha256(cp) != cal.get("calibrator_sha256")):
        raise RuntimeError("Frozen model/calibration provenance mismatch")
    policy = Path(policy)
    policy_info = json.loads(policy.read_text())
    if (policy_info.get("status") != "POST_HOC_REVIEW_POLICY_V2_SIMULATION_ONLY"
            or policy_info.get("model") != MODEL_NAME
            or policy_info.get("model_sha256") != digest
            or policy_info.get("calibrator_sha256") != cal["calibrator_sha256"]
            or policy_info.get("split_manifest_sha256") != cal["split_manifest_sha256"]
            or policy_info.get("block_enabled") is not False
            or policy_info.get("blocks") != 0
            or policy_info.get("review_budget_fraction") != 0.01
            or policy_info.get("tie_rule") != "inclusive cutoff; arrival-order prefix cap"):
        raise RuntimeError("Policy provenance or simulation safeguards mismatch")
    threshold = policy_info.get("calibration_threshold")
    if (type(threshold) not in (float, int)
            or not np.isfinite(threshold) or not 0 < threshold < 1):
        raise RuntimeError("Invalid frozen policy threshold")
    # Freeze the policy boundary: edits to the report must not silently
    # change the risk threshold used by the local lab.
    if not np.isclose(threshold, 0.00528866346387857, rtol=0, atol=1e-15):
        raise RuntimeError("Frozen policy threshold mismatch")
    # The archived policy v2 was generated by this project.
    if not (policy_info.get("policy_rows") == 526517
            and policy_info.get("policy_frauds") == 412):
        raise RuntimeError("Unexpected policy cohort")

    model = joblib.load(model_path)
    calibrator = joblib.load(cp)
    if (getattr(model, "n_features_in_", None) != len(INDICES)
            or getattr(calibrator, "n_features_in_", None) != 1
            or float(calibrator.coef_[0, 0]) <= 0):
        raise RuntimeError("Frozen model/calibrator interface mismatch")

    def score(full_features):
        array = np.asarray(full_features, dtype=np.float32)
        if array.shape != (1, 21):
            raise ValueError("Expected one 21-column full-context vector")
        margin = np.asarray(model.decision_function(array[:, INDICES]),
                            dtype=np.float64)
        risk = float(calibrator.predict_proba(margin.reshape(-1, 1))[0, 1])
        if not np.isfinite(risk) or not 0 <= risk <= 1:
            raise RuntimeError("Invalid fitted simulation score")
        return risk

    return score, float(threshold), ("lab-v2-" + file_sha256(policy)[:16]), (
        MODEL_NAME + "-" + digest[:16]
    )


def open_local_lab(db_path, privacy_key, password, *,
                   candidates=CANDIDATES, calibration=CALIBRATION,
                   policy=POLICY_OUTPUT / "policy.json"):
    if not isinstance(password, str) or len(password) < 16:
        raise RuntimeError("Local lab requires a password >=16 characters")
    if not isinstance(privacy_key, str) or len(privacy_key) < 16:
        raise RuntimeError("Local lab requires a private account pseudonymization key")
    score, threshold, policy_version, model_version = load_frozen_lab_artifacts(
        candidates, calibration, policy
    )
    owner = {}

    def choose_action(risk):
        j = owner["journal"]
        # Executed while the journal holds its lock and BEGIN IMMEDIATE.
        # Query the committed + current transaction scope via the same
        # SQLite connection, so restart and duplicates do not reset quota.
        # These counters reflect committed rows only and are rebuilt from
        # SQLite on restart. Avoid scanning the growing table per transaction.
        total = j.committed_events
        reviewed = j.reviewed_events
        if reviewed < 0 or reviewed > total:
            raise RuntimeError("Journal decision count mismatch")
        capacity = (total + 1) // 100
        return ("REVIEW" if risk >= threshold and reviewed < capacity
                else "ALLOW")

    journal = FullContextJournal(
        db_path, score, choose_action,
        model_version=model_version, policy_version=policy_version,
        privacy_key=privacy_key, block_enabled=False,
    )
    owner["journal"] = journal
    app = create_full_context_app(
        journal, auth_password=password,
        scoring_source="POST_HOC_PAYSIM_LOCAL_LAB_NOT_DEPLOYABLE",
    )
    return app, journal


def main():
    if os.getenv("FGZ_FULL_CONTEXT_LAB_ACK") != "SIMULATION_ONLY":
        raise RuntimeError("Set FGZ_FULL_CONTEXT_LAB_ACK=SIMULATION_ONLY explicitly")
    if os.getenv("FGZ_DEPLOYMENT_MODE", "local") != "local":
        raise RuntimeError("Production deployment is prohibited for this lab")
    password = os.getenv("FGZ_AUTH_PASSWORD")
    privacy_key = os.getenv("FGZ_PRIVACY_KEY")
    app, journal = open_local_lab(
        Path(os.getenv("FGZ_FULL_CONTEXT_DB_PATH", str(DB_DEFAULT))).expanduser(),
        privacy_key, password,
    )
    try:
        print("Full-context exploratory PaySim simulator: http://127.0.0.1:5051")
        print("No real payments; BLOCK disabled. Fresh DB means empty prior history.")
        app.run(host="127.0.0.1", port=5051, threaded=False,
                debug=False, use_reloader=False)
    finally:
        journal.close()


if __name__ == "__main__":
    main()
